test('Claude -> Abrir un navegador, click en el boton Register, validar que los mensajes de error sean visibles, recargar la pagina, validar que los mensajes de error no sean visibles',
    async ({ page }) => {
        await page.goto('/');

        const firstNameError = page.getByText('Valid first name is required');
        const lastNameError = page.getByText('Valid last name is required');
        const emailError = page.getByText('Please enter a valid email address');
        const visibleErrors = page.locator('.invalid-feedback').filter({ visible: true });

        await page.getByRole('button', { name: 'Register' }).click();
        await expect(firstNameError).toBeVisible();
        await expect(lastNameError).toBeVisible();
        await expect(emailError).toBeVisible();
        await expect(visibleErrors).toHaveCount(3);

        await page.reload();
        await expect(firstNameError).toBeHidden();
        await expect(lastNameError).toBeHidden();
        await expect(emailError).toBeHidden();
        await expect(visibleErrors).toHaveCount(0);
    }
);