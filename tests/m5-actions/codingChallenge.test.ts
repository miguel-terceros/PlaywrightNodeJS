import { test, expect } from "@playwright/test";

test('Codigng -> Click on Register button, validate errors, Reload page, validate errors not visible',
    async ({ page }) => {

        await page.goto('/');

        const msgs = page.locator('.invalid-feedback');

        await page.getByRole('button', { name: 'Register' }).click();
        await expect(msgs).toHaveCount(3);
        for(const msg of await msgs.all()) {
            await expect(msg).toBeVisible();
        }

        await page.reload()
        for(const msg of await msgs.all()) {
            await expect(msg).toBeHidden();
        }
    }
);

